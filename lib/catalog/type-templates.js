/** @param {string} key */
export function findTypeTemplate(key) {
  return TYPE_TEMPLATES.find((template) => template.key === key) ?? null;
}

/** Templates as the admin picker lists them (no attribute lists or charts). */
export function typeTemplateSummaries() {
  return TYPE_TEMPLATES.map((template) => ({
    key: template.key,
    name: template.name,
    pluralName: template.pluralName,
    icon: template.icon,
    description: template.description,
    details: template.fields.map(([key]) => ATTRIBUTE_PRESETS[key]?.name ?? key),
    options: template.options.map((option) => ATTRIBUTE_PRESETS[option.key]?.name ?? option.key),
    hasSizeChart: Boolean(template.sizeChart),
  }));
}
